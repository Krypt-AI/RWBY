/**
 * Regenerates src/data/games/mlbbHeroes.ts: every MLBB hero with its lanes, classes,
 * portrait and Moonton's official counter relations, read from the Rone Arena API
 * (an unofficial mirror of the in-game academy). Run it when a new patch lands:
 *
 *   npm run data:mlbb
 *
 * The snapshot keeps the game-room counter helper working when the live API is down.
 */
import { writeFile } from 'node:fs/promises'

const API_BASE = 'https://arena.rone.dev/api'
const OUTPUT = new URL('../src/data/games/mlbbHeroes.ts', import.meta.url)
const CLASSES = ['tank', 'fighter', 'assassin', 'mage', 'marksman', 'support']
const LANES = { 'Exp Lane': 'exp', Jungle: 'jungle', 'Mid Lane': 'mid', 'Gold Lane': 'gold', Roam: 'roam' }

async function getRecords(path, params = {}) {
  const url = new URL(API_BASE + path)
  for (const [key, value] of Object.entries({ size: 300, index: 1, ...params })) url.searchParams.append(key, value)
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)
  const body = await response.json()
  if (body.code !== 0) throw new Error(`${url}: ${body.message}`)
  return body.data.records.map(record => record.data)
}

const ids = list => list.filter(Boolean)

/** Prints values the way the codebase writes them: single quotes, spaced lists and objects. */
function literal(value) {
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  return String(value)
}

const toSource = row => `{ ${Object.entries(row).map(([key, value]) => `${key}: ${literal(value)}`).join(', ')} }`

const [heroes, catalog, ...classLists] = await Promise.all([
  getRecords('/heroes', { order: 'asc' }),
  getRecords('/academy/heroes/catalog'),
  ...CLASSES.map(role => getRecords('/academy/heroes', { role })),
])

const catalogById = new Map(catalog.map(entry => [entry.hero_id, entry]))
const classesById = new Map()
CLASSES.forEach((role, index) => {
  for (const entry of classLists[index]) classesById.set(entry.hero_id, [...(classesById.get(entry.hero_id) ?? []), role])
})

const rows = heroes.map(hero => {
  const entry = catalogById.get(hero.hero_id)
  const lanes = (entry?.hero.data.roadsort ?? [])
    .map(road => LANES[road?.data?.road_sort_title])
    .filter(Boolean)
  return `  ${toSource({
    id: hero.hero_id,
    name: hero.hero.data.name,
    portrait: entry?.head ?? hero.hero.data.head,
    lanes,
    classes: classesById.get(hero.hero_id) ?? [],
    counters: ids(hero.relation.strong.target_hero_id),
    counteredBy: ids(hero.relation.weak.target_hero_id),
  })},`
})

const today = new Date().toISOString().slice(0, 10)

await writeFile(
  OUTPUT,
  `import type { DraftHero } from './types'

/**
 * Generated by scripts/fetch-mlbb-heroes.mjs on ${today}. Do not edit by hand.
 * Every hero with lanes, classes and Moonton's official counter relations, read from the
 * Rone Arena API (an unofficial mirror of the in-game academy). The game-room counter helper
 * falls back to these relations when the live matchup stats can't be reached.
 */
export const MLBB_HEROES: DraftHero[] = [
${rows.join('\n')}
]
`,
)

console.log(`Wrote ${rows.length} heroes to ${OUTPUT.pathname}`)
